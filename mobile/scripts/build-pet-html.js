// Inlines src/widget/assets/pet-web/{index.html,css/*.css,engine.js} into one
// self-contained HTML string and writes src/widget/petHtml.js.
//
// Why: react-native-webview's `source={{ html }}` string is the only way to
// load local multi-file HTML/CSS/JS that works identically on Android, iOS
// and Expo Go — requiring index.html as a Metro asset and hoping relative
// <link>/<script> paths resolve at runtime is fragile and differs by
// platform. Run this again whenever pet-web/ changes.

const fs = require('fs');
const path = require('path');

const webDir = path.join(__dirname, '..', 'src', 'widget', 'assets', 'pet-web');
const outFile = path.join(__dirname, '..', 'src', 'widget', 'petHtml.js');

let html = fs.readFileSync(path.join(webDir, 'index.html'), 'utf8');

html = html.replace(/<link rel="stylesheet" href="css\/([\w-]+)\.css">/g, (_m, name) => {
  const css = fs.readFileSync(path.join(webDir, 'css', `${name}.css`), 'utf8');
  return `<style>\n${css}\n</style>`;
});

html = html.replace(/<script src="engine\.js"><\/script>/, () => {
  const js = fs.readFileSync(path.join(webDir, 'engine.js'), 'utf8');
  return `<script>\n${js}\n</script>`;
});

const out = `// AUTO-GENERATED by scripts/build-pet-html.js — do not edit by hand.
// Edit src/widget/assets/pet-web/ instead, then re-run:
//   node scripts/build-pet-html.js
export const PET_HTML = ${JSON.stringify(html)};
`;

fs.writeFileSync(outFile, out, 'utf8');
console.log(`Wrote ${path.relative(process.cwd(), outFile)} (${html.length} chars inlined)`);
